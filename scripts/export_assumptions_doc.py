#!/usr/bin/env python3
"""Export live assumptions from database to docs/ASSUMPTIONS.md."""

import sqlite3
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DB_PATH = REPO_ROOT / "backend" / "festos.db"
OUTPUT_PATH = REPO_ROOT / "docs" / "ASSUMPTIONS.md"

conn = sqlite3.connect(str(DB_PATH))
c = conn.cursor()
c.execute("SELECT key, value, source, owner, reason, impact_if_changed FROM assumption ORDER BY key")
rows = c.fetchall()

lines = [
    "# FestOS Authoritative Assumptions Register (`docs/ASSUMPTIONS.md`)",
    "",
    "> **Festival:** Aarohan (EPINOIA 2026, IIM Indore)  ",
    "> **Lifecycle:** Seeded into database table `assumption`, fully editable via ChangeService (`PUT /api/v1/assumptions/{key}`), and owned by operational leads.",
    "",
    "## 1. Operating Philosophy",
    "- **Assumptions are first-class assets:** Heuristics are never called optimal. Schedules generated by FestOS are marked `ASSUMED`.",
    "- **Visible, Owned, and Sourced:** Every parameter has an operational owner, origin source, rationale, and documented blast radius if adjusted.",
    "- **Audited Evolution:** Modifying an assumption writes an immutable audit record and recalculates dependent downstreams through `ChangeService`.",
    "",
    "## 2. Live Master Assumption Table",
    "",
    "| Key | Live Value | Source | Owner | Rationale | Impact if Changed |",
    "|---|---|---|---|---|---|",
]

for key, val, src, owner, reason, impact in rows:
    clean_val = str(val).replace("|", "\\|")
    clean_reason = str(reason).replace("|", "\\|")
    clean_impact = str(impact).replace("|", "\\|")
    lines.append(f"| `{key}` | `{clean_val}` | {src} | **{owner}** | {clean_reason} | {clean_impact} |")

lines.extend([
    "",
    "## 3. Domain Deep-Dives",
    "",
    "### 3.1 Accommodation & Turnaround",
    "- **`cleaning_buffer_minutes` (180 min):** Spec decision explicitly establishes a 3-hour turnaround buffer between room occupants. Room turnaround failure cascades into check-in queues.",
    "- **`minor_age_threshold` (18):** Participants aged 17 (279 participants in data pack) require guardian consent and are restricted from unchaperoned external property allocation.",
    "- **`external_budget_inr` (NULL):** Budget is deliberately unset in data pack. The system runs in budget-unset mode, alerting the Festival Director to configure spend ceilings.",
    "- **`accom_plan_c_weights` (Cohesion 0.5, Cost 0.3, Travel 0.2):** Explicit weighting parameters balancing university group togetherness with financial cost and shuttle travel times.",
    "",
    "### 3.2 Transport & Transit Windows",
    "- **`late_night_start` (22:00) / `late_night_end` (06:00):** City transit boundary. Arrivals or departures during this window require mandatory security escorts and dedicated shuttles.",
    "- **`shuttle_capacity_seats` (12 seats), `shuttle_vehicle_count` (3 vehicles), `shuttle_travel_min` (25 min):** Operational transit baseline for campus-to-hotel loops.",
    "",
    "### 3.3 Event Scheduling & Competitions",
    "- **`setup_buffer_min` (15 min) & `teardown_buffer_min` (15 min):** Stage and AV turnaround time enforced before and after every session.",
    "- **`round_result_buffer_min` (60 min):** Deliberation and tabulation window required between preliminary heats, semifinals, and finals.",
    "- **`semifinal_ratio` (0.50), `finalist_ratio` (0.10), `finalist_min` (8 entrants):** Deterministic progression ratios advancing entrants across elimination rounds.",
    "",
    "### 3.4 Headcount Reconciliation",
    "- **`expected_participants_narrative` (2,400):** Initial marketing prospectus target. Kept side-by-side with raw imported count (2,836) and contingent declared strength (2,842).",
    "- **No Forced Truncation:** FestOS refuses to silently drop 436 participants; all 2,836 participants are tracked, reconciled, and audited.",
])

OUTPUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Exported {len(rows)} live assumptions to {OUTPUT_PATH}")
