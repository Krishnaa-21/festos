test.describe("FestOS Operations UI Acceptance Flows (Prompt 12)", () => {
  test.beforeEach(async ({ page }) => {
    await setupOpsMocks(page);

    // Pre-populate authentication in localStorage
    await page.addInitScript(() => {
      localStorage.setItem("festos_token", "mock_ops_jwt_token_2026");
      localStorage.setItem(
        "festos_user",
        JSON.stringify({
          id: "usr_dir_001",
          email: "director@festos.internal",
          full_name: "Dr. Devashish Roy",
          role: "FESTIVAL_DIRECTOR",
          permissions: ["*"],
        })
      );
    });
  });

  // Acceptance 1: An Event Lead resolves a clash
  test("Journey 1: Event Lead resolves a schedule conflict via the Conflict Panel with ranked candidate and justification", async ({
    page,
  }) => {
    // Navigate to Events & Venues workspace
    await page.goto("/events");

    // Verify Gantt Timeline loads with prominent ASSUMED badge
    await expect(page.locator("text=ASSUMED SCHEDULE").first()).toBeVisible();

    // Click Conflict Panel tab
    await page.click("button:has-text('Conflict Panel')");

    // Verify Schedule Conflicts Engine header and conflict item
    await expect(page.locator("text=Schedule Conflicts Engine")).toBeVisible();
    await expect(page.locator("text=Main Auditorium (V01) assigned to two concurrent sessions")).toBeVisible();
    await expect(page.locator("text=59 people affected")).toBeVisible();

    // Click Ranked Resolutions button to open resolution candidates drawer
    await page.click("button:has-text('Ranked Resolutions')");

    // Verify Ranked Candidates drawer is displayed
    await expect(page.locator("text=Ranked Candidates (Evaluated by Engine)")).toBeVisible();
    await expect(page.locator("text=+2 resolved").first()).toBeVisible();

    // Click Apply Candidate button
    await page.click("button:has-text('Apply Candidate')");

    // Verify ConfirmWithReason modal opens
    await expect(page.locator("text=Apply Schedule Resolution")).toBeVisible();

    // Type operational rationale in required reason field
    const reasonInput = page.locator("textarea[placeholder*='Specify operational rationale']");
    await reasonInput.fill("Shifted start time to 11:45 after buffer to resolve auditorium contention");

    // Click Apply via ChangeService
    await page.click("button:has-text('Apply via ChangeService')");

    // Modal closes
    await expect(page.locator("text=Apply Schedule Resolution")).not.toBeVisible();
  });

  // Acceptance 2: A volunteer sees ALREADY ISSUED on a rescan
  test("Journey 2: Volunteer scans merchandise QR twice and sees huge ALREADY ISSUED panel with original metadata on repeat scan", async ({
    page,
  }) => {
    // Navigate to Merchandise workspace
    await page.goto("/merchandise");

    // Switch to Counter Mode
    await page.click("button:has-text('Counter Mode (Volunteers)')");

    // Verify volunteer counter scanner is visible
    await expect(page.locator("text=Participant QR / ID Scanner")).toBeVisible();

    // Input participant ID P0042
    const manualInput = page.locator("input[placeholder*='Enter Participant ID or Card Code']");
    await manualInput.fill("P0042");

    // First scan: Click Verify & Issue Merchandise
    await page.click("button:has-text('Verify & Issue Merchandise')");

    // Huge Green ISSUED panel appears
    await expect(page.locator("text=ISSUED").first()).toBeVisible();
    await expect(page.locator("text=Festival Kit Issued Successfully")).toBeVisible();

    // Second scan with the same ID
    await manualInput.fill("P0042");
    await page.click("button:has-text('Verify & Issue Merchandise')");

    // Huge Red ALREADY ISSUED panel appears
    await expect(page.locator("text=ALREADY ISSUED").first()).toBeVisible();
    await expect(page.locator("text=Duplicate scan rejected! This item was previously claimed")).toBeVisible();
    await expect(page.locator("text=counter_north_01")).toBeVisible();
    await expect(page.locator("text=usr_vol_01")).toBeVisible();
    await expect(page.locator("button:has-text('Request Manager Void / Override')")).toBeVisible();
  });

  // Acceptance 3: A Food Ops Manager completes a vendor shutdown from the UI
  test("Journey 3: Food Ops Manager completes emergency vendor shutdown with lost capacity, replacement selection, and notifications", async ({
    page,
  }) => {
    // Navigate to Food & Vendors workspace
    await page.goto("/food");

    // Verify Dietary Coverage Matrix loads
    await expect(page.locator("text=Dietary Coverage Matrix")).toBeVisible();

    // Switch to Vendors & Commercial Rates tab
    await page.click("button:has-text('Vendors & Commercial Rates')");

    // Find vendor Spice Junction
    await expect(page.locator("text=Spice Junction")).toBeVisible();

    // Click Emergency Shutdown on Spice Junction
    const shutdownButtons = page.locator("button:has-text('Emergency Shutdown')");
    await shutdownButtons.nth(1).click();

    // Verify Emergency Vendor Shutdown modal opens
    await expect(page.locator("text=Emergency Vendor Shutdown: Spice Junction")).toBeVisible();

    // Verify lost capacity and cost delta
    await expect(page.locator("text=-350 meals / slot")).toBeVisible();
    await expect(page.locator("text=+7,000 INR")).toBeVisible();

    // Verify ranked replacement #1 Royal Feast Caterers
    await expect(page.locator("text=Royal Feast Caterers").first()).toBeVisible();

    // Verify notification drafts checkbox
    await expect(page.locator("text=Approve & Dispatch Notifications")).toBeVisible();

    // Fill in mandatory justification
    const reasonTextarea = page.locator("textarea[placeholder*='Enter reason for shutting down this vendor']");
    await reasonTextarea.fill("Severe hygiene violation detected during food safety audit");

    // Click Confirm Shutdown & Reassign
    await page.click("button:has-text('Confirm Shutdown & Reassign')");

    // Modal closes
    await expect(page.locator("text=Emergency Vendor Shutdown: Spice Junction")).not.toBeVisible();
  });
});
