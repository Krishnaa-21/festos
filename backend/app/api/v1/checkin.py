# OWNER: P2
from __future__ import annotations

from typing import Any, Dict, List

from app.core.db import get_session
from app.core.deps import require_permission
from app.schemas.checkin import (
    ArrivalUpdateRequest,
    CheckinRequest,
    CheckoutRequest,
    SyncBatchRequest,
    SyncBatchResponseData,
)
from app.schemas.common import Actor, Envelope
from app.services.checkin.service import (
    checkin_participant,
    checkout_participant,
    get_arrival_board,
    get_participant_checkin_detail,
    get_reallocation_suggestions,
    search_checkin_participants,
    sync_offline_operations,
    update_participant_arrival,
)
from fastapi import APIRouter, Depends, Query
from sqlmodel import Session

router = APIRouter(prefix="/checkin", tags=["Checkin"])


@router.get("/board", response_model=Envelope[Dict[str, Any]])
def get_checkin_board(
    actor: Actor = Depends(require_permission("checkin:read")),
    session: Session = Depends(get_session),
):
    """Real-time arrival desk board tracking pending arrivals, checked-in, and late arrivals."""
    data = get_arrival_board(session)
    return Envelope(data=data)


@router.get("/search", response_model=Envelope[List[Dict[str, Any]]])
def search_participants_endpoint(
    q: str = Query(..., min_length=1, description="Search query string"),
    actor: Actor = Depends(require_permission("checkin:read")),
    session: Session = Depends(get_session),
):
    """Rapid desk search by participant ID, name, email, or contingent code."""
    results = search_checkin_participants(session, query=q)
    return Envelope(data=results, meta={"total": len(results)})


@router.get("/participant/{id}", response_model=Envelope[Dict[str, Any]])
def get_participant_detail_endpoint(
    id: str,
    actor: Actor = Depends(require_permission("checkin:read")),
    session: Session = Depends(get_session),
):
    """Retrieve participant check-in profile with room assignment, readiness, and alerts."""
    data = get_participant_checkin_detail(session, participant_id=id)
    return Envelope(data=data)


@router.post("/checkin", response_model=Envelope[Dict[str, Any]])
@router.post("/verify-arrival", response_model=Envelope[Dict[str, Any]])
def checkin_endpoint(
    body: CheckinRequest,
    actor: Actor = Depends(require_permission("checkin:write")),
    session: Session = Depends(get_session),
):
    """Idempotent participant check-in with room cleaning readiness verification."""
    result = checkin_participant(session, req=body, actor=actor)
    return Envelope(data=result, meta={"client_op_id": body.client_op_id})


@router.post("/checkout", response_model=Envelope[Dict[str, Any]])
def checkout_endpoint(
    body: CheckoutRequest,
    actor: Actor = Depends(require_permission("checkin:write")),
    session: Session = Depends(get_session),
):
    """Check out participant, free bed, and trigger room cleaning countdown buffer."""
    result = checkout_participant(session, req=body, actor=actor)
    return Envelope(data=result, meta={"client_op_id": body.client_op_id})


@router.patch("/participant/{id}/arrival", response_model=Envelope[Dict[str, Any]])
def update_arrival_endpoint(
    id: str,
    body: ArrivalUpdateRequest,
    actor: Actor = Depends(require_permission("checkin:write")),
    session: Session = Depends(get_session),
):
    """Update participant arrival datetime, flagging curfew breaches."""
    result = update_participant_arrival(session, participant_id=id, req=body, actor=actor)
    warnings = []
    if result.get("is_curfew_breach"):
        warnings.append("Late night arrival past campus curfew (22:00).")
    return Envelope(data=result, warnings=warnings)


@router.post("/sync", response_model=Envelope[SyncBatchResponseData])
def sync_offline_batch_endpoint(
    body: SyncBatchRequest,
    actor: Actor = Depends(require_permission("checkin:write")),
    session: Session = Depends(get_session),
):
    """Batch synchronize buffered offline desk operations with conflict explanations."""
    result = sync_offline_operations(session, req=body, actor=actor)
    return Envelope(data=result)


@router.get("/reallocations/suggestions", response_model=Envelope[Dict[str, Any]])
def get_reallocation_suggestions_endpoint(
    actor: Actor = Depends(require_permission("checkin:read")),
    session: Session = Depends(get_session),
):
    """Retrieve advisory bed reallocation suggestions generated by cancellations/no-shows."""
    suggestions = get_reallocation_suggestions(session)
    return Envelope(
        data={"suggestions": suggestions},
        meta={"count": len(suggestions)},
        warnings=["Suggestions are advisory only. FestOS never auto-applies reallocation without organizer sign-off."],
    )
